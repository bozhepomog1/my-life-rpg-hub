-- Life RPG Hub — проверка, что приватность держится НА УРОВНЕ БАЗЫ,
-- а не только скрытием элементов в интерфейсе.
--
-- Смысл: все запросы ниже имитируют прямой API-вызов в обход UI. Если
-- ограничение реализовано только во фронтенде, здесь оно не сработает и
-- данные утекут — то есть этот файл специально пытается достать то, чего
-- доставать нельзя.
--
-- КАК ЗАПУСКАТЬ (Dashboard → SQL Editor → New query):
-- SQL Editor ходит в базу под ролью postgres, которая RLS игнорирует, —
-- поэтому просто вставить запросы недостаточно, надо явно переключиться
-- на роль authenticated и подставить конкретного пользователя, как это
-- делает настоящий клиент со своим JWT. Именно это и делает
-- set_config('request.jwt.claims', ...) ниже.
--
-- Подставь три реальных uuid из своей базы (взять: select user_id,
-- username, short_code, is_private from public.profiles;):
--   :me       — от чьего имени «заходим»
--   :stranger — тот, с кем у :me НЕТ ни дружбы, ни заявки
--   :friend   — тот, с кем у :me ЕСТЬ принятая заявка (для теста 5-6)
-- и один короткий код приватного пользователя.

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 0. Входим как обычный пользователь (не postgres).
-- ═════════════════════════════════════════════════════════════
begin;
set local role authenticated;
select set_config(
  'request.jwt.claims',
  json_build_object('sub', '<ПОДСТАВЬ_UUID_ME>', 'role', 'authenticated')::text,
  true
);

-- Контроль: должно вернуть подставленный uuid. Если null — дальнейшие
-- тесты ничего не проверяют, все политики будут видеть anon.
select auth.uid() as acting_as;

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 1. Массовая выгрузка профилей. ГЛАВНЫЙ ТЕСТ.
--
-- Это ровно то, что раньше делал GET /rest/v1/profiles?select=*
-- при политике using(true) — отдавал ВСЮ таблицу.
--
-- ОЖИДАЕМО: количество = 1 (я сам) + число моих принятых друзей.
-- НЕ должно быть равно общему числу пользователей в приложении.
-- ═════════════════════════════════════════════════════════════
select count(*) as rows_i_can_read from public.profiles;

-- Для сравнения — сколько их всего (эту строку RLS не ограничивает, так
-- как считает подзапрос от имени владельца таблицы… поэтому смотрим
-- отдельно, уже после rollback, под postgres):
--   select count(*) from public.profiles;

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 2. Прямое чтение строки постороннего по его uuid.
-- ОЖИДАЕМО: 0 строк.
-- ═════════════════════════════════════════════════════════════
select * from public.profiles where user_id = '<ПОДСТАВЬ_UUID_STRANGER>';

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 3. Прямое чтение по короткому коду в обход RPC.
-- Раньше так работал поиск друзей; теперь единственный легальный путь —
-- функция find_profile_by_code (тест 4).
-- ОЖИДАЕМО: 0 строк.
-- ═════════════════════════════════════════════════════════════
select * from public.profiles where short_code = '<КОД_ПРИВАТНОГО>';

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 4. Поиск приватного пользователя по коду через RPC.
--
-- Приватность «мягкая»: найти и добавить в друзья можно всегда.
-- ОЖИДАЕМО: РОВНО 1 строка, в ней есть username/avatar/short_code,
-- is_private = true, НО total_xp, level, fitness_index = NULL.
-- Если прогресс не NULL — приватность не работает.
-- ═════════════════════════════════════════════════════════════
select * from public.find_profile_by_code('<КОД_ПРИВАТНОГО>');

-- Для контраста: у открытого пользователя те же поля должны быть
-- заполнены числами.
select * from public.find_profile_by_code('<КОД_ОТКРЫТОГО>');

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 5. Попытка выкачать базу через пакетную RPC, подсунув ей чужие
-- uuid, с которыми у меня нет никакой связи.
-- ОЖИДАЕМО: посторонние в результат не попадают вообще (0 строк, либо
-- только те из списка, кто мне друг / с кем висит заявка).
-- ═════════════════════════════════════════════════════════════
select * from public.get_visible_profiles(
  array['<ПОДСТАВЬ_UUID_STRANGER>', '<ПОДСТАВЬ_UUID_FRIEND>']::uuid[]
);

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 6. Детали профиля (статы, стрики, достижения) постороннего.
-- ОЖИДАЕМО: 0 строк.
-- А та же выборка для '<ПОДСТАВЬ_UUID_FRIEND>' должна вернуть 1 строку —
-- принятый друг видит всё как обычно, даже если он приватный.
-- ═════════════════════════════════════════════════════════════
select * from public.friend_profiles where user_id = '<ПОДСТАВЬ_UUID_STRANGER>';
select * from public.friend_profiles where user_id = '<ПОДСТАВЬ_UUID_FRIEND>';

-- ═════════════════════════════════════════════════════════════
-- ТЕСТ 7. Чужой игровой стейт (квесты, питание, замеры, фото).
-- ОЖИДАЕМО: 0 строк — и до, и после этой миграции.
-- ═════════════════════════════════════════════════════════════
select user_id from public.game_states where user_id <> auth.uid();

rollback;

-- ═════════════════════════════════════════════════════════════
-- После rollback (снова под postgres) — общее число пользователей,
-- чтобы сравнить с результатом ТЕСТА 1.
-- ═════════════════════════════════════════════════════════════
select count(*) as total_users from public.profiles;
